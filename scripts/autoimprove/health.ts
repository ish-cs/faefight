/**
 * Health aggregation: client error reports (from /api/errors) and sim invariant violations (self-play
 * training matches, re-simulated human replays) grouped into stable signatures with counts and
 * first/last seen, rendered to docs/auto-health.md together with the auto-fix attempt log.
 */

export type ClientReport = { build: string; kind: string; message: string; stack?: string; replayId?: string; tick?: number; count?: number; at?: string };

/** A sim violation with enough context to reproduce it headlessly. */
export type SimFinding = {
  signature: string;
  kind: string;
  detail: string;
  tick: number;
  /** Self-play: the match setup + seed. Human replay: the replay file. */
  repro: { type: 'seed'; seed: number; setup: unknown } | { type: 'replay'; file: string };
};

export type Sample = { message: string; stack?: string; build?: string; replayId?: string; tick?: number; repro?: SimFinding['repro'] };

export type Signature = {
  signature: string;
  source: 'client' | 'sim';
  count: number;
  firstSeen: string;
  lastSeen: string;
  sample: Sample;
};

export type FixAttempt = { at: string; signature: string; outcome: 'accepted' | 'rejected' | 'skipped'; reason: string; branch?: string; commit?: string };

export type HealthState = { signatures: Record<string, Signature>; attempts: FixAttempt[] };

export const emptyHealth = (): HealthState => ({ signatures: {}, attempts: [] });

/** Strip run-to-run noise (numbers, hashes in bundle names, URLs) so the same bug groups together. */
export function normalizeMessage(s: string): string {
  return s
    .replace(/https?:\/\/[^\s)]+\/([^/\s):]+)/g, '$1')
    .replace(/-[A-Za-z0-9_]{8}\.js/g, '-*.js')
    .replace(/0x[0-9a-f]+/gi, 'N')
    .replace(/\d+(\.\d+)?/g, 'N')
    .replace(/\s+/g, ' ')
    .trim()
    .slice(0, 160);
}

/** Top stack frame's function + file (no line numbers: they shift with every build). */
export function topFrame(stack?: string): string {
  if (!stack) return '';
  for (const line of stack.split('\n')) {
    const m = line.match(/at (?:(\S+) \()?(?:.*\/)?([^/\s:()]+)(?::\d+){0,2}\)?/) ?? line.match(/^(\S*)@(?:.*\/)?([^/\s:]+)/);
    if (m && m[2]) return `${m[1] ?? '?'}@${normalizeMessage(m[2])}`;
  }
  return '';
}

export function clientSignature(r: ClientReport): string {
  const f = topFrame(r.stack);
  return `client:${r.kind}:${normalizeMessage(r.message)}${f ? ` ${f}` : ''}`;
}

export function ingestClient(h: HealthState, reports: ClientReport[], now: string): void {
  for (const r of reports) {
    if (r.kind === 'longframe') { bump(h, 'client:longframe', 'client', r.count ?? 1, r.at ?? now, { message: r.message, build: r.build }); continue; }
    bump(h, clientSignature(r), 'client', r.count ?? 1, r.at ?? now, { message: r.message, stack: r.stack, build: r.build, replayId: r.replayId, tick: r.tick });
  }
}

export function ingestSim(h: HealthState, findings: SimFinding[], now: string): void {
  for (const f of findings) bump(h, `sim:${f.signature}`, 'sim', 1, now, { message: f.detail, tick: f.tick, repro: f.repro });
}

function bump(h: HealthState, sig: string, source: Signature['source'], n: number, at: string, sample: Sample) {
  const s = h.signatures[sig];
  if (!s) { h.signatures[sig] = { signature: sig, source, count: n, firstSeen: at, lastSeen: at, sample }; return; }
  s.count += n;
  if (at < s.firstSeen) s.firstSeen = at;
  if (at > s.lastSeen) s.lastSeen = at;
  // Prefer a sample we can reproduce.
  if (!s.sample.repro && sample.repro) s.sample = sample;
}

/** Signatures worth an automatic fix attempt: not attempted in the last `cooldownDays`, most frequent first. */
export function fixCandidates(h: HealthState, now: Date, cooldownDays = 7): Signature[] {
  const recent = new Set(h.attempts.filter((a) => now.getTime() - Date.parse(a.at) < cooldownDays * 86_400_000).map((a) => a.signature));
  return Object.values(h.signatures)
    .filter((s) => !recent.has(s.signature) && s.signature !== 'client:longframe')
    .sort((a, b) => b.count - a.count || (a.lastSeen < b.lastSeen ? 1 : -1));
}

const esc = (s: string) => s.replace(/\|/g, '\\|').replace(/\n/g, ' ');

export function renderHealth(h: HealthState, now: string): string {
  const sigs = Object.values(h.signatures).sort((a, b) => b.count - a.count);
  const lastAttempt = new Map(h.attempts.map((a) => [a.signature, a] as const));
  const lines = [
    '# Auto health',
    '',
    `Generated by \`scripts/auto-improve.ts\` (${now}). Do not edit by hand: it is rewritten every run.`,
    '',
    'Sources: client error reports (`/api/errors`) and sim invariant violations found in self-play training matches and re-simulated uploaded replays (`src/sim/invariants.ts`).',
    '',
    '## Signatures',
    '',
  ];
  if (sigs.length === 0) lines.push('None seen yet.');
  else {
    lines.push('| Signature | Source | Count | First seen | Last seen | Last fix attempt |', '|---|---|---|---|---|---|');
    for (const s of sigs) {
      const a = lastAttempt.get(s.signature);
      lines.push(`| \`${esc(s.signature)}\` | ${s.source} | ${s.count} | ${s.firstSeen.slice(0, 16)} | ${s.lastSeen.slice(0, 16)} | ${a ? `${a.outcome} (${esc(a.reason)})` : '—'} |`);
    }
  }
  lines.push('', '## Fix attempts', '');
  if (h.attempts.length === 0) lines.push('None yet.');
  else {
    lines.push('| When | Signature | Outcome | Reason | Branch / commit |', '|---|---|---|---|---|');
    for (const a of [...h.attempts].reverse()) lines.push(`| ${a.at.slice(0, 16)} | \`${esc(a.signature)}\` | ${a.outcome} | ${esc(a.reason)} | ${a.branch ?? ''}${a.commit ? ` ${a.commit}` : ''} |`);
  }
  return lines.join('\n') + '\n';
}
