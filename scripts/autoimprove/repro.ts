/// <reference types="node" />
/**
 * Generated reproduction tests for sim invariant signatures. A self-play finding replays its exact
 * MatchSpec (seed + seats); a human-replay finding re-runs the uploaded replay (copied next to the
 * test as a fixture). Either way the test asserts the signature does not occur, so it fails while the
 * bug exists and passes once it is fixed.
 */
import fs from 'node:fs';
import path from 'node:path';
import type { Signature } from './health';

const TICK_HZ = 30;

export function reproTestSource(sig: Signature, reproPath: string, fixtureRel?: string): string | null {
  const repro = sig.sample.repro;
  if (!repro || sig.source !== 'sim') return null;
  const signature = sig.signature.replace(/^sim:/, '');
  const up = path.posix.relative(path.posix.dirname(reproPath), '.') || '.';
  const tick = sig.sample.tick ?? 0;
  const header = [
    `// Auto-generated by scripts/autoimprove (auto-fix). Signature: ${signature}`,
    `// Detail when found: ${(sig.sample.message ?? '').replace(/\n/g, ' ').slice(0, 200)}`,
    "import { expect, test } from 'vitest';",
  ];
  if (repro.type === 'seed') {
    const spec = repro.setup as { maxSec: number };
    // Stop a little after the tick it was seen at (whole match for "never ends").
    const maxSec = signature.startsWith('neverEnds') ? spec.maxSec : Math.min(spec.maxSec, Math.ceil(tick / TICK_HZ) + 10);
    return [
      ...header,
      `import { runMatch, type MatchSpec } from '${up}/scripts/train/runMatch';`,
      '',
      `const SIG = ${JSON.stringify(signature)};`,
      `const SPEC = ${JSON.stringify({ ...spec, maxSec })} as MatchSpec;`,
      '',
      `test(\`self-play seed ${repro.seed}: no \${SIG}\`, async () => {`,
      '  const r = await runMatch(SPEC);',
      '  expect((r.violations ?? []).filter((v) => v.signature === SIG)).toEqual([]);',
      '}, 900_000);',
      '',
    ].join('\n');
  }
  if (!fixtureRel) return null;
  return [
    ...header,
    "import { fileURLToPath } from 'node:url';",
    `import { replayViolations } from '${up}/scripts/autoimprove/trainer';`,
    '',
    `const SIG = ${JSON.stringify(signature)};`,
    '',
    `test(\`uploaded replay: no \${SIG} by tick ${tick + 300}\`, async () => {`,
    `  const sigs = await replayViolations(fileURLToPath(new URL(${JSON.stringify(fixtureRel)}, import.meta.url)), ${tick + 300});`,
    '  expect(sigs.filter((s) => s === SIG)).toEqual([]);',
    '}, 900_000);',
    '',
  ].join('\n');
}

/** Write the repro test (and replay fixture) into `dir`; false when the signature can't be reproduced headlessly. */
export function writeReproTest(dir: string, sig: Signature, reproPath: string): boolean {
  const repro = sig.sample.repro;
  let fixtureRel: string | undefined;
  if (repro?.type === 'replay') {
    if (!fs.existsSync(repro.file)) return false;
    fixtureRel = `fixtures/${path.basename(reproPath, '.test.ts')}.faereplay`;
    const dest = path.join(dir, path.dirname(reproPath), fixtureRel);
    fs.mkdirSync(path.dirname(dest), { recursive: true });
    fs.copyFileSync(repro.file, dest);
  }
  const src = reproTestSource(sig, reproPath, fixtureRel);
  if (!src) return false;
  fs.mkdirSync(path.join(dir, path.dirname(reproPath)), { recursive: true });
  fs.writeFileSync(path.join(dir, reproPath), src);
  return true;
}
