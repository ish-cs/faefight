/** "the shotgun" etc. for {w}. Unknown kinds read as-is. */
export const WEAPON_PHRASE: Record<string, string> = {
  fists: 'bare hands', pistol: 'the pistol', smg: 'the SMG', shotgun: 'the shotgun', rifle: 'the rifle',
  rocket: 'the rocket launcher', grenade: 'a grenade', charge: 'a breach charge',
  storm: 'the storm', lightning: 'lightning', barrel: 'barrel', propane: 'propane tank', trap: 'spike trap',
};

export const weaponPhrase = (w: unknown): string => (typeof w === 'string' ? WEAPON_PHRASE[w] ?? w : 'a big hit');

/** Fill a template's placeholders. Throws on a placeholder with no value (a template bug, caught by tests). */
export function fill(tpl: string, vars: Vars): string {
  return tpl.replace(/\{([a-z])\}/g, (_m, k: string) => {
    const v = vars[k as Var];
    if (v === undefined) throw new Error(`[commentary] template needs {${k}}: "${tpl}"`);
    return String(v);
  });
}
